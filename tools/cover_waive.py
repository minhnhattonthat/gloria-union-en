"""Text-coverage waivers by window class: the gate's waive file from a tour's coverage logs.

    python -X utf8 tools/cover_waive.py work/qa/cover work/qa/cover/strings.tsv [--manual docs/text_unreached.tsv]
        [--out docs/text_unshown.tsv]

A string the tour never drew is waived when another string of the same window class (tools/boxes.py budget class;
story and common text: the dialogue window) was drawn on the tour: same window, same draw path, width linted by
boxes.py (decision D18). --manual holds "id<TAB>reason" lines written by hand for the rest (unreachable or debug
text). Prints the classes with no string drawn and the strings left; exit 1 if any string is neither shown nor waived.
Then: python -X utf8 $SKILL/scripts/textcover.py work/qa/cover work/qa/cover/strings.tsv --waive docs/text_unshown.tsv
"""
import argparse, collections, glob, json, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import boxes


FIXED = {   # classes whose unshown strings get a fixed reason instead of a class match
    'sys': 'PSP system dialog text (sceUtility save/load/install), drawn by the firmware, not the game\'s writer: '
           'the text hook cannot log it',
    boxes.I_DEFAULT[0]: 'code-built single string (i: slot) that no tour scene reached; its window is unmeasured '
                        '(lint default 1/21/20/3): NOT seen in game',
}


def klass(e):
    if e['id'][0] in 'sc': return 'dialogue'   # story and common text all goes to the dialogue window
    b = boxes.budget(e)
    return b[2] if b else None


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('cover'); ap.add_argument('strings')
    ap.add_argument('--manual', default='docs/text_unreached.tsv'); ap.add_argument('--out', default='docs/text_unshown.tsv')
    a = ap.parse_args()
    ids = {}
    for line in open(a.strings, encoding='utf8'):
        sid, h = line.rstrip('\n').split('\t'); ids[h.lower()] = sid
    shown = {}   # id -> scene
    for log in sorted(glob.glob(os.path.join(a.cover, '**', 'log.txt'), recursive=True)):
        scene = os.path.basename(os.path.dirname(log))
        for line in open(log, encoding='utf8'):
            if line.startswith('TEXT '): shown.setdefault(ids[line.split()[1].lower()], scene)
    manual = {}
    if os.path.exists(a.manual):
        for line in open(a.manual, encoding='utf8'):
            p = line.rstrip('\n').split('\t')
            if len(p) > 1 and p[1].strip() and not p[0].startswith('#'): manual[p[0]] = p[1]
    entries = [e for f in sorted(glob.glob('script/**/*.json', recursive=True)) for e in json.load(open(f, encoding='utf8'))
               if e.get('en') and e.get('status') != 'data' and e['id'] in ids.values()]
    first = {}   # class -> (id, scene) of a string drawn on the tour
    cls = {e['id']: klass(e) for e in entries}
    for e in entries:
        if e['id'] in shown and cls[e['id']]: first.setdefault(cls[e['id']], (e['id'], shown[e['id']]))
    waive, left = [], collections.defaultdict(list)
    for e in entries:
        i, k = e['id'], cls[e['id']]
        if i in shown: continue
        if i in manual: waive.append(f'{i}\t{manual[i]}')
        elif k in FIXED: waive.append(f'{i}\t{FIXED[k]}')
        elif k in first: waive.append(f'{i}\tclass {k}: same window as {first[k][0]} (drawn in {first[k][1]})')
        else: left[k].append(i)
    with open(a.out, 'w', encoding='utf8', newline='\n') as f:
        f.write('# generated by tools/cover_waive.py (D18): strings the tour never drew, waived by window class\n')
        f.write('\n'.join(waive) + '\n')
    for k, v in sorted(left.items(), key=lambda kv: -len(kv[1])):
        print(f'NO CLASS DRAWN  {k}  {len(v)}: {" ".join(v[:8])}{" ..." if len(v) > 8 else ""}')
    n = sum(map(len, left.values()))
    print(f'{len(shown)} shown, {len(waive)} waived, {n} left', file=sys.stderr)
    sys.exit(1 if n else 0)


if __name__ == '__main__':
    main()
